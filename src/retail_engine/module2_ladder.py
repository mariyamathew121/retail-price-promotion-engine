"""Record how the median log-log OLS elasticity moves as controls are added."""

from __future__ import annotations

import argparse
from pathlib import Path

import duckdb
import numpy as np
import pandas as pd

from retail_engine.module2 import (
    WEEKLY_SQL,
    _calendar_week_numbers,
    _ols_log_log,
    _weekly_control_matrix,
)

# Column order of _weekly_control_matrix: sin, cos, snap, event, promo.
CALENDAR_CONTROLS = 4
SPECIFICATIONS = (
    "no_controls",
    "seasonality_snap_event",
    "plus_promo_flag",
    "plus_promo_flag_and_linear_trend",
)


def control_ladder_for_series(weekly: pd.DataFrame) -> dict[str, float]:
    """Return the OLS elasticity of one weekly series under each specification."""
    weekly = weekly.sort_values("week_start", kind="stable").reset_index(drop=True)
    controls = _weekly_control_matrix(weekly)
    log_price = np.log(weekly["price"].to_numpy(dtype=np.float64))
    log_units = np.log1p(weekly["units_sold"].to_numpy(dtype=np.float64))
    week_indices = _calendar_week_numbers(weekly["week_start"])
    trend = ((week_indices - week_indices.mean()) / week_indices.std())[:, None]
    matrices = {
        "no_controls": np.zeros((len(weekly), 0)),
        "seasonality_snap_event": controls[:, :CALENDAR_CONTROLS],
        "plus_promo_flag": controls,
        "plus_promo_flag_and_linear_trend": np.hstack([controls, trend]),
    }
    estimates = {}
    for name, matrix in matrices.items():
        try:
            estimates[name] = _ols_log_log(log_price, log_units, matrix, week_indices)[0]
        except ValueError:
            estimates[name] = float("nan")
    return estimates


def control_ladder(weekly: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for (item_id, store_id), group in weekly.groupby(["item_id", "store_id"], sort=True):
        rows.append(
            {"item_id": item_id, "store_id": store_id, **control_ladder_for_series(group)}
        )
    return pd.DataFrame(rows, columns=["item_id", "store_id", *SPECIFICATIONS])


def _summary_markdown(ladder: pd.DataFrame) -> str:
    medians = ladder[list(SPECIFICATIONS)].median()
    lines = [
        "# Module 2 control ladder",
        "",
        f"Median OLS log-log elasticity over {len(ladder)} selected item-store series "
        "(`log1p(units)` on `log(price)`, weekly, same series as the DML run).",
        "",
        "| Controls | Median OLS elasticity |",
        "|---|---:|",
    ]
    lines += [f"| {name} | {medians[name]:.3f} |" for name in SPECIFICATIONS]
    lines += [
        "",
        "`promo_flag` is derived from price (a drop of at least 10% below the "
        "prior eight-week maximum), so adding it removes much of the deep-discount "
        "variation from the treatment. The large move from the second to the third "
        "row therefore mixes confounding control with lost price variation, and the "
        "trend row shows how sensitive the result is to specification. Generated by "
        "`module2-control-ladder`.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input", type=Path, default=Path("data/processed/clean_retail_data.parquet")
    )
    parser.add_argument(
        "--series",
        type=Path,
        default=Path("data/processed/module2/price_elasticities_selected_combinations.csv"),
    )
    parser.add_argument(
        "--output", type=Path, default=Path("data/processed/module2/control_ladder.csv")
    )
    parser.add_argument(
        "--summary", type=Path, default=Path("outputs/module2/control_ladder.md")
    )
    args = parser.parse_args()
    shortlisted = pd.read_csv(args.series)[["item_id", "store_id"]]
    connection = duckdb.connect()
    connection.register("shortlisted", shortlisted)
    weekly = connection.execute(WEEKLY_SQL, [str(args.input)]).df()
    ladder = control_ladder(weekly)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    ladder.to_csv(args.output, index=False)
    args.summary.parent.mkdir(parents=True, exist_ok=True)
    args.summary.write_text(_summary_markdown(ladder), encoding="utf-8")
    print(ladder[list(SPECIFICATIONS)].median().round(3).to_string())


if __name__ == "__main__":
    main()
