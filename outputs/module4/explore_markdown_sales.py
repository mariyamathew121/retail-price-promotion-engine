"""Create descriptive, non-causal summaries of the synthetic markdown data."""

from __future__ import annotations

import hashlib
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[2]
INPUT_PATH = PROJECT_ROOT / "data" / "raw" / "markdown" / "SYNTHETIC Markdown Dataset.csv"
OUTPUT_DIR = PROJECT_ROOT / "data" / "processed" / "module4"
REPORT_PATH = PROJECT_ROOT / "outputs" / "module4" / "markdown_sales_exploration.md"
PLOT_PATH = PROJECT_ROOT / "outputs" / "module4" / "markdown_sales_exploration.png"
SUMMARY_PATH = OUTPUT_DIR / "markdown_stage_response_quintiles.csv"

STAGES = [
    (f"Markdown_{number}", f"Sales_After_M{number}")
    for number in range(1, 5)
]
REQUIRED_COLUMNS = {
    "Product_ID",
    "Category",
    "Historical_Sales",
    *(column for pair in STAGES for column in pair),
}


def build_stage_summaries(frame: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    missing_columns = sorted(REQUIRED_COLUMNS - set(frame.columns))
    if missing_columns:
        raise ValueError(f"Dataset is missing required columns: {missing_columns}")

    analysis = frame.drop_duplicates().copy()
    if analysis["Historical_Sales"].le(0).any():
        raise ValueError("Historical_Sales must be positive to calculate relative lift")

    quintile_rows: list[dict[str, float | int | str]] = []
    overall_rows: list[dict[str, float | int | str]] = []
    for stage_number, (markdown_column, sales_column) in enumerate(STAGES, start=1):
        markdown = analysis[markdown_column]
        uplift = (analysis[sales_column] - analysis["Historical_Sales"]) / analysis[
            "Historical_Sales"
        ]
        quintiles = pd.qcut(markdown, q=5, labels=False, duplicates="drop")
        stage_frame = pd.DataFrame(
            {
                "markdown_quintile": quintiles + 1,
                "markdown": markdown,
                "uplift": uplift,
            }
        )
        summary = (
            stage_frame.groupby("markdown_quintile", observed=True)
            .agg(
                row_count=("uplift", "size"),
                markdown_min=("markdown", "min"),
                markdown_max=("markdown", "max"),
                markdown_median=("markdown", "median"),
                uplift_median=("uplift", "median"),
                uplift_mean=("uplift", "mean"),
                positive_uplift_share=("uplift", lambda values: values.gt(0).mean()),
            )
            .reset_index()
        )
        for record in summary.to_dict(orient="records"):
            quintile_rows.append(
                {
                    "stage": f"M{stage_number}",
                    **record,
                }
            )
        overall_rows.append(
            {
                "stage": f"M{stage_number}",
                "row_count": int(len(analysis)),
                "markdown_median": float(markdown.median()),
                "uplift_median": float(uplift.median()),
                "uplift_mean": float(uplift.mean()),
                "positive_uplift_share": float(uplift.gt(0).mean()),
                "spearman_rank_correlation": float(
                    markdown.rank().corr(uplift.rank())
                ),
            }
        )

    return pd.DataFrame(quintile_rows), pd.DataFrame(overall_rows)


def _format_pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def _render_report(
    frame: pd.DataFrame,
    source_sha256: str,
    summaries: pd.DataFrame,
    overall: pd.DataFrame,
) -> str:
    overall_rows = "\n".join(
        f"| {row.stage} | {row.row_count:,} | "
        f"{_format_pct(row.markdown_median)} | {_format_pct(row.uplift_median)} | "
        f"{_format_pct(row.uplift_mean)} | "
        f"{_format_pct(row.positive_uplift_share)} | "
        f"{row.spearman_rank_correlation:.3f} |"
        for row in overall.itertuples(index=False)
    )
    quintile_rows = "\n".join(
        f"| {row.stage} | Q{int(row.markdown_quintile)} | "
        f"{row.markdown_min:.2f}–{row.markdown_max:.2f} | "
        f"{row.row_count:,} | {_format_pct(row.uplift_median)} | "
        f"{_format_pct(row.uplift_mean)} |"
        for row in summaries.itertuples(index=False)
    )
    return f"""# Module 4 — exploratory markdown/sales associations

## Provenance and method

- Source: `data/raw/markdown/SYNTHETIC Markdown Dataset.csv`
- SHA-256: `{source_sha256}`
- Source rows: {len(frame):,}; exact duplicates removed for this analysis:
  {int(frame.duplicated().sum()):,}; analysis rows:
  {len(frame.drop_duplicates()):,}.
- Generated by: `outputs/module4/explore_markdown_sales.py`
- Summary table: `data/processed/module4/markdown_stage_response_quintiles.csv`
- Figure: `outputs/module4/markdown_sales_exploration.png`

For each numbered stage, the descriptive outcome is
`(Sales_After_Mi - Historical_Sales) / Historical_Sales`. Each corresponding
`Markdown_i` field is grouped into five data-derived quantile bins. `Optimal
Discount` is deliberately excluded. The fields are paired by their names only;
the dataset provides no stage definitions, dates, exposure windows, or
experimental assignment. The file describes itself as synthetic.

## Overall stage summaries

| Stage | Products | Median markdown | Median sales difference vs historical | Mean sales difference vs historical | Products above historical sales | Spearman rank correlation |
|---|---:|---:|---:|---:|---:|---:|
{overall_rows}

## Descriptive summaries by markdown quantile

The markdown range shown is the observed minimum–maximum in that quintile.
Sales differences are relative to the supplied `Historical_Sales`; they are
not incremental causal effects.

| Stage | Markdown quintile | Observed markdown range | Products | Median sales difference vs historical | Mean sales difference vs historical |
|---|---|---:|---:|---:|---:|
{quintile_rows}

## Interpretation

Median sales differences are positive in the supplied stage fields, and
markdown rank correlations are positive in this dataset. This does not show
that markdowns caused the reported sales changes. Baseline and post-markdown
measurement windows may differ, product assignment and inventory are
uncontrolled, the file is synthetic, and the ordered M1–M4 fields are not
documented as time periods. The summaries are suitable only as exploratory
descriptions of this file—not as demand curves, discount recommendations,
profit/ROI estimates, or a markdown schedule. See
`outputs/module4/markdown_dataset_audit.md` for quality checks and data gaps.
"""


def _save_plot(summaries: pd.DataFrame) -> None:
    colors = ["#1769AA", "#D97732", "#7552A3", "#B84A55"]
    figure, axis = plt.subplots(figsize=(8.5, 5.2))
    for stage_number, stage in enumerate(("M1", "M2", "M3", "M4")):
        stage_rows = summaries.loc[summaries["stage"].eq(stage)]
        axis.plot(
            stage_rows["markdown_median"] * 100,
            stage_rows["uplift_median"] * 100,
            marker="o",
            linewidth=1.8,
            color=colors[stage_number],
            label=stage,
        )
    axis.axhline(0, color="#777777", linewidth=0.9, linestyle="--")
    axis.set_xlabel("Markdown field value (%) — provisional fraction interpretation")
    axis.set_ylabel("Median sales difference vs historical (%)")
    axis.set_title("Synthetic D2: descriptive stage associations, not causal effects")
    axis.grid(alpha=0.22)
    axis.legend(title="Matched field pair")
    figure.tight_layout()
    figure.savefig(PLOT_PATH, dpi=160)
    plt.close(figure)


def main() -> None:
    if not INPUT_PATH.is_file():
        raise FileNotFoundError(f"Markdown dataset not found: {INPUT_PATH}")

    source_bytes = INPUT_PATH.read_bytes()
    frame = pd.read_csv(INPUT_PATH)
    summaries, overall = build_stage_summaries(frame)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    summaries.to_csv(SUMMARY_PATH, index=False)
    _save_plot(summaries)
    REPORT_PATH.write_text(
        _render_report(
            frame,
            hashlib.sha256(source_bytes).hexdigest(),
            summaries,
            overall,
        ),
        encoding="utf-8",
    )
    print(f"Source rows: {len(frame):,}")
    print(f"Exact duplicate rows excluded from analysis: {int(frame.duplicated().sum()):,}")
    print("Stage-level descriptive summaries:")
    print(overall.to_string(index=False))
    print(f"Report: {REPORT_PATH}")
    print(f"Summary table: {SUMMARY_PATH}")
    print(f"Figure: {PLOT_PATH}")


if __name__ == "__main__":
    main()
